// ---- land raster ----
static uint8_t g_mask[180][360];
static bool g_built = false;

static bool inside(const Poly& p, double lat, double lon) {
    bool in = false;
    int n = p.n;
    for (int i = 0, j = n - 1; i < n; j = i++) {
        double yi = p.ll[i * 2], xi = p.ll[i * 2 + 1];
        double yj = p.ll[j * 2], xj = p.ll[j * 2 + 1];
        if ((yi > lat) != (yj > lat) && lon < (xj - xi) * (lat - yi) / (yj - yi) + xi) in = !in;
    }
    return in;
}

void buildMask() {
    if (g_built) return;
    for (int la = 0; la < 180; la++) {
        for (int lo = 0; lo < 360; lo++) {
            double lat = -90.0 + la + 0.5, lon = -180.0 + lo + 0.5;
            bool land = false;
            for (int i = 0; i < polyCount(); i++) {
                if (kPolys[i].water) continue;
                if (inside(kPolys[i], lat, lon)) { land = true; break; }
            }
            if (land)
                for (int i = 0; i < polyCount(); i++)
                    if (kPolys[i].water && inside(kPolys[i], lat, lon)) { land = false; break; }
            g_mask[la][lo] = land ? 1 : 0;
        }
    }
    g_built = true;
}

bool isLand(double lat, double lon) {
    if (!g_built) return false;
    int la = (int)floor(lat + 90.0), lo = (int)floor(lon + 180.0);
    if (la < 0) la = 0;
    if (la > 179) la = 179;
    lo %= 360; if (lo < 0) lo += 360;
    return g_mask[la][lo] != 0;
}

